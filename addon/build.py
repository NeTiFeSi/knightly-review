"""Build the add-on.

    python3 build.py          # dist/knightly_review.ankiaddon (double-click to install)
    python3 build.py --dev    # only fill knightly_review/vendor and knightly_review/card in place,
                              # for a symlinked development copy

Bundles:
- knightly_review/vendor/: the core (../core/knightly) and the pinned packages in vendor.txt,
  with their imports made relative (see vendoring.py);
- knightly_review/card/: the card UI build (../card/dist: _knightly.js and templates).
  Run `npm run build` in card/ first.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import shutil
import sys
import tarfile
import urllib.request
import zipfile
from pathlib import Path

from vendoring import vendor_tree

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PKG = HERE / "knightly_review"
VENDOR = PKG / "vendor"
CARD = PKG / "card"
CACHE = HERE / ".vendor-cache"


def pinned() -> list[tuple[str, str, str]]:
    out = []
    for line in (HERE / "vendor.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, version, sha = line.split()
            out.append((name, version, sha))
    return out


def sdist(name: str, version: str, sha: str) -> bytes:
    CACHE.mkdir(exist_ok=True)
    cached = CACHE / f"{name}-{version}.tar.gz"
    if not cached.exists():
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as r:
            files = json.load(r)["urls"]
        url = next(f["url"] for f in files if f["packagetype"] == "sdist")
        with urllib.request.urlopen(url) as r:
            cached.write_bytes(r.read())
    data = cached.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha:
        cached.unlink()
        sys.exit(f"{name} {version}: sha256 mismatch (vendor.txt says {sha})")
    return data


def vendor() -> None:
    packages = pinned()
    names = {n for n, _, _ in packages}
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    VENDOR.mkdir(parents=True)
    (VENDOR / "__init__.py").write_text('"""Bundled pure-Python packages. Generated by build.py; do not edit."""\n')
    tmp = CACHE / "src"
    if tmp.exists():
        shutil.rmtree(tmp)
    for name, version, sha in packages:
        with tarfile.open(fileobj=io.BytesIO(sdist(name, version, sha))) as t:
            members = [m for m in t.getmembers() if m.isfile() and f"/{name}/" in f"/{m.name}"]
            t.extractall(tmp, members=members)
        src = next(tmp.glob(f"{name}-{version}/{name}"))
        vendor_tree(src, VENDOR / name, names)
    vendor_tree(ROOT / "core" / "knightly", VENDOR / "knightly", names)
    licence = "\n".join(f"{n} {v}: GPL-3.0-or-later compatible, see https://pypi.org/project/{n}/{v}/" for n, v, _ in packages)
    (VENDOR / "VENDORED.txt").write_text(licence + "\nknightly: this repository's core/ (GPL-3.0-or-later)\n")


def card() -> None:
    dist = ROOT / "card" / "dist"
    need = [dist / "_knightly.js", dist / "_kr_stockfish.js", dist / "_kr_stockfish.wasm",
            dist / "templates" / "front.html", dist / "templates" / "back.html", dist / "templates" / "style.css"]
    missing = [str(p) for p in need if not p.exists()]
    if missing:
        sys.exit("card build missing (run `npm run build` in card/): " + ", ".join(missing))
    if CARD.exists():
        shutil.rmtree(CARD)
    CARD.mkdir()
    for p in need:
        shutil.copy2(p, CARD / p.name)


def package() -> Path:
    out = HERE / "dist" / "knightly_review.ankiaddon"
    out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(PKG.rglob("*")):
            rel = f.relative_to(PKG)
            if not f.is_file() or "__pycache__" in f.parts or rel.parts[0] == "user_files" or f.name == "meta.json":
                continue
            z.write(f, rel)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev", action="store_true", help="only refresh vendor/ and card/ in place")
    args = ap.parse_args()
    vendor()
    card()
    if not args.dev:
        print(package())


if __name__ == "__main__":
    main()
